import ast
import logging
from datetime import datetime
from pathlib import Path

import numpy as np
import optuna
import pandas as pd
import torch
import torch.nn as nn
from rnn_trainer import RNNModel
from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
from sklearn.model_selection import TimeSeriesSplit
from sklearn.preprocessing import StandardScaler
from time_series_dataset import TimeSeriesDataset
from torch.utils.data import DataLoader

RANDOM_STATE = 42
DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")

np.random.seed(RANDOM_STATE)
torch.manual_seed(RANDOM_STATE)
if torch.cuda.is_available():
    torch.cuda.manual_seed(RANDOM_STATE)


class ImprovementLinks:
    """
    Run optimization only on links selected automatically from the CSV
    generated by PredictionAllLinks.

    The selection is based on simple_comparison_summary.csv.
    For each selected link:
      - baseline file = <link>_baseline_<best_baseline_method>.csv
      - stacking file = <link>_stacking.csv
      - baseline model = best_baseline_model
      - stacking model = best_stacking_model

    Optionally, parameter ranges are inferred from simple_models_detail.csv.
    """

    def __init__(
        self,
        path_links="files_filtered",
        summary_csv="simple_comparison_summary.csv",
        detail_csv="simple_models_detail.csv",
        top_k=5,
        selection_mode="lowest_improvement",
        improvement_threshold=None,
        cv_splits=5,
    ):
        self.path_links = Path(path_links)
        self.summary_csv = Path(summary_csv)
        self.detail_csv = Path(detail_csv)
        self.top_k = top_k
        self.selection_mode = selection_mode
        self.improvement_threshold = improvement_threshold
        self.cv_splits = cv_splits

    def setup_logger(self):
        Path("logs").mkdir(exist_ok=True)
        ts = datetime.now().strftime("%Y%m%d_%H%M%S")
        log_path = Path("logs") / f"prediction_filtered_auto_{ts}.log"
        logging.basicConfig(
            level=logging.INFO,
            format="%(asctime)s | %(levelname)7s | %(message)s",
            handlers=[
                logging.FileHandler(log_path, encoding="utf-8"),
                logging.StreamHandler(),
            ],
        )
        return logging.getLogger(__name__), log_path

    def safe_load_csv(self, fp):
        try:
            return pd.read_csv(fp)
        except Exception:
            return pd.read_csv(fp, sep=";")

    def parse_params(self, value):
        if isinstance(value, dict):
            return value
        if pd.isna(value):
            return {}
        if isinstance(value, str):
            value = value.strip()
            if not value:
                return {}
            try:
                return ast.literal_eval(value)
            except Exception:
                return {}
        return {}

    def load_selection_from_summary(self):
        if not self.summary_csv.exists():
            raise FileNotFoundError(f"Summary CSV not found: {self.summary_csv}")

        df = self.safe_load_csv(self.summary_csv)

        required_cols = [
            "link",
            "best_baseline_method",
            "best_baseline_model",
            "best_stacking_model",
            "improvement_pct",
        ]
        missing = [c for c in required_cols if c not in df.columns]
        if missing:
            raise ValueError(
                f"Missing required columns in {self.summary_csv}: {missing}"
            )

        df = df.copy()
        df["improvement_pct"] = pd.to_numeric(df["improvement_pct"], errors="coerce")
        df = df.dropna(subset=["link", "best_baseline_method", "improvement_pct"])

        if self.improvement_threshold is not None:
            df = df[df["improvement_pct"] <= self.improvement_threshold]

        if self.selection_mode == "lowest_improvement":
            df = df.sort_values("improvement_pct", ascending=True)
        elif self.selection_mode == "highest_improvement":
            df = df.sort_values("improvement_pct", ascending=False)
        else:
            raise ValueError(
                "selection_mode must be 'lowest_improvement' or 'highest_improvement'"
            )

        if self.top_k is not None:
            df = df.head(self.top_k)

        return df.reset_index(drop=True)

    def load_detail_reference(self):
        if not self.detail_csv.exists():
            return pd.DataFrame()

        df = self.safe_load_csv(self.detail_csv).copy()
        if "params" in df.columns:
            df["params_dict"] = df["params"].apply(self.parse_params)
        else:
            df["params_dict"] = [{} for _ in range(len(df))]
        return df

    def find_reference_params(self, df_detail, link, variant, model):
        """
        variant: 'baseline' or 'stacking'
        model: 'RandomForest', 'LSTM', 'GRU'
        """
        if df_detail.empty:
            return {}

        rows = df_detail[
            (df_detail["link"] == link)
            & (df_detail["variant"] == variant)
            & (df_detail["model"] == model)
        ]

        if rows.empty:
            return {}

        row = rows.sort_values("rmse", ascending=True).iloc[0]
        return row.get("params_dict", {}) or {}

    def build_rf_ranges(self, ref_params):
        n_estimators = int(ref_params.get("n_estimators", 300))
        max_depth_ref = ref_params.get("max_depth", None)

        if max_depth_ref is None:
            max_depth_range = (4, 20)
        else:
            max_depth_ref = int(max_depth_ref)
            max_depth_range = (max(2, max_depth_ref - 4), max_depth_ref + 4)

        return {
            "n_estimators": (max(50, n_estimators - 80), n_estimators + 80),
            "max_depth": max_depth_range,
            "min_samples_leaf": (1, 6),
        }

    def build_dl_ranges(self, ref_params):
        window = int(ref_params.get("window", 24))
        hidden_size = int(ref_params.get("hidden_size", 64))
        num_layers = int(ref_params.get("num_layers", 2))
        dropout = float(ref_params.get("dropout", 0.1))
        lr = float(ref_params.get("lr", 1e-3))
        epochs = int(ref_params.get("epochs", 25))

        lr_low = max(1e-5, lr / 10)
        lr_high = min(1e-1, lr * 10)

        return {
            "window": (max(6, window - 12), window + 12),
            "hidden_size": (max(16, hidden_size - 32), hidden_size + 32),
            "num_layers": (max(1, num_layers - 1), num_layers + 1),
            "dropout": (max(0.0, dropout - 0.15), min(0.5, dropout + 0.15)),
            "lr": (lr_low, lr_high),
            "epochs": (max(10, epochs - 10), epochs + 10),
        }

    def get_param_ranges(self, model_type, ref_params):
        if model_type == "RandomForest":
            return self.build_rf_ranges(ref_params)
        return self.build_dl_ranges(ref_params)

    def build_supervised(self, df, target_col="Atraso(ms)", lags=6):
        if "Data" in df.columns:
            df["Data"] = pd.to_datetime(df["Data"], errors="coerce")
            df = df.sort_values("Data")
            df.set_index("Data", inplace=True)

        for lag in range(1, lags + 1):
            df[f"lag_{lag}"] = df[target_col].shift(lag)

        df[f"rolling_mean_{lags}"] = df[target_col].rolling(lags).mean().shift(1)

        for c in ["Hop_count", "Bottleneck", "Vazao_BBR", "mask_applied"]:
            if c in df.columns:
                df[c] = pd.to_numeric(df[c], errors="coerce")

        df = df.dropna()
        y = df[target_col].astype(float)
        X = df.drop(columns=[target_col])
        return X, y

    def prepare_dl_data(self, df, target_col="Atraso(ms)"):
        if "Data" in df.columns:
            df["Data"] = pd.to_datetime(df["Data"], errors="coerce")
            df = df.sort_values("Data")
            df.set_index("Data", inplace=True)
        elif "Date" in df.columns:
            df["Date"] = pd.to_datetime(df["Date"], errors="coerce")
            df = df.sort_values("Date")
            df.set_index("Date", inplace=True)

        numeric_cols = [target_col]
        for c in ["Hop_count", "Bottleneck", "Vazao_BBR", "mask_applied"]:
            if c in df.columns:
                df[c] = pd.to_numeric(df[c], errors="coerce")
                numeric_cols.append(c)

        data = df[numeric_cols].dropna()

        scaler = StandardScaler()
        data_scaled = scaler.fit_transform(data)

        return data_scaled, scaler

    def compute_metrics(self, y_true, y_pred):
        rmse = np.sqrt(mean_squared_error(y_true, y_pred))
        mae = mean_absolute_error(y_true, y_pred)
        eps = 1e-8
        mape = np.mean(np.abs((y_true - y_pred) / (np.abs(y_true) + eps))) * 100
        r2 = r2_score(y_true, y_pred)
        return {"rmse": rmse, "mae": mae, "mape": mape, "r2": r2}

    def train_rf_cv(self, X, y, params, cv_splits=5):
        model = RandomForestRegressor(
            n_estimators=params.get("n_estimators", 100),
            max_depth=params.get("max_depth", None),
            min_samples_leaf=params.get("min_samples_leaf", 1),
            random_state=RANDOM_STATE,
            n_jobs=-1,
        )
        tscv = TimeSeriesSplit(n_splits=cv_splits)
        metrics_accum = []

        for train_idx, test_idx in tscv.split(X):
            X_tr, X_te = X.iloc[train_idx], X.iloc[test_idx]
            y_tr, y_te = y.iloc[train_idx], y.iloc[test_idx]
            model.fit(X_tr, y_tr)
            pred = model.predict(X_te)
            metrics_accum.append(self.compute_metrics(y_te.values, pred))

        agg = {
            k: float(np.mean([m[k] for m in metrics_accum])) for k in metrics_accum[0]
        }
        agg["params"] = params
        return agg

    def optimize_rf_params(self, X, y, param_ranges, cv_splits=5, n_trials=50):
        def objective(trial):
            params = {
                "n_estimators": trial.suggest_int(
                    "n_estimators",
                    param_ranges["n_estimators"][0],
                    param_ranges["n_estimators"][1],
                ),
                "max_depth": trial.suggest_int(
                    "max_depth",
                    param_ranges["max_depth"][0],
                    param_ranges["max_depth"][1],
                ),
                "min_samples_leaf": trial.suggest_int(
                    "min_samples_leaf",
                    param_ranges["min_samples_leaf"][0],
                    param_ranges["min_samples_leaf"][1],
                ),
            }

            model = RandomForestRegressor(
                n_estimators=params["n_estimators"],
                max_depth=params["max_depth"],
                min_samples_leaf=params["min_samples_leaf"],
                random_state=RANDOM_STATE,
                n_jobs=-1,
            )

            tscv = TimeSeriesSplit(n_splits=cv_splits)
            rmse_scores = []

            for train_idx, test_idx in tscv.split(X):
                X_tr, X_te = X.iloc[train_idx], X.iloc[test_idx]
                y_tr, y_te = y.iloc[train_idx], y.iloc[test_idx]
                model.fit(X_tr, y_tr)
                pred = model.predict(X_te)
                rmse_scores.append(np.sqrt(mean_squared_error(y_te, pred)))

            return np.mean(rmse_scores)

        optuna.logging.set_verbosity(optuna.logging.WARNING)
        study = optuna.create_study(direction="minimize")
        study.optimize(objective, n_trials=n_trials, show_progress_bar=False)

        best_params = study.best_params
        metrics = self.train_rf_cv(X, y, best_params, cv_splits)
        return best_params, metrics

    def train_dl_model(self, model, train_loader, val_loader, epochs, lr, patience=10):
        criterion = nn.MSELoss()
        optimizer = torch.optim.Adam(model.parameters(), lr=lr)
        scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(
            optimizer, patience=max(1, patience // 3), factor=0.5
        )

        best_val_loss = float("inf")
        best_model_state = None
        patience_counter = 0

        for _ in range(epochs):
            model.train()
            for X_batch, y_batch in train_loader:
                X_batch, y_batch = X_batch.to(DEVICE), y_batch.to(DEVICE)

                optimizer.zero_grad()
                outputs = model(X_batch)
                loss = criterion(outputs, y_batch)
                loss.backward()
                optimizer.step()

            model.eval()
            val_loss = 0.0
            with torch.no_grad():
                for X_batch, y_batch in val_loader:
                    X_batch, y_batch = X_batch.to(DEVICE), y_batch.to(DEVICE)
                    outputs = model(X_batch)
                    loss = criterion(outputs, y_batch)
                    val_loss += loss.item()

            val_loss /= max(1, len(val_loader))
            scheduler.step(val_loss)

            if val_loss < best_val_loss:
                best_val_loss = val_loss
                best_model_state = {
                    k: v.detach().cpu().clone() for k, v in model.state_dict().items()
                }
                patience_counter = 0
            else:
                patience_counter += 1
                if patience_counter >= patience:
                    break

        if best_model_state is not None:
            model.load_state_dict(best_model_state)

        return model

    def train_dl_cv(self, data_scaled, scaler, params, model_type, cv_splits=5):
        window = params["window"]
        hidden_size = params["hidden_size"]
        num_layers = params["num_layers"]
        dropout = params["dropout"]
        lr = params["lr"]
        epochs = params["epochs"]

        tscv = TimeSeriesSplit(n_splits=cv_splits)
        metrics_accum = []

        for train_idx, test_idx in tscv.split(data_scaled):
            train_data = data_scaled[train_idx]
            test_data = data_scaled[test_idx]

            if len(train_data) <= window or len(test_data) <= window:
                continue

            train_dataset = TimeSeriesDataset(train_data, window)
            test_dataset = TimeSeriesDataset(test_data, window)

            train_loader = DataLoader(train_dataset, batch_size=32, shuffle=True)
            test_loader = DataLoader(test_dataset, batch_size=32, shuffle=False)

            input_size = data_scaled.shape[1]
            model = RNNModel(
                input_size, hidden_size, num_layers, model_type, dropout
            ).to(DEVICE)

            model = self.train_dl_model(model, train_loader, test_loader, epochs, lr)

            model.eval()
            predictions = []
            actuals = []

            with torch.no_grad():
                for X_batch, y_batch in test_loader:
                    X_batch = X_batch.to(DEVICE)
                    outputs = model(X_batch)
                    predictions.extend(outputs.cpu().numpy().ravel())
                    actuals.extend(y_batch.numpy().ravel())

            if predictions:
                pred_full = np.zeros((len(predictions), data_scaled.shape[1]))
                actual_full = np.zeros((len(actuals), data_scaled.shape[1]))
                pred_full[:, 0] = predictions
                actual_full[:, 0] = actuals

                pred_denorm = scaler.inverse_transform(pred_full)[:, 0]
                actual_denorm = scaler.inverse_transform(actual_full)[:, 0]

                metrics_accum.append(self.compute_metrics(actual_denorm, pred_denorm))

        if not metrics_accum:
            return {
                "rmse": float("nan"),
                "mae": float("nan"),
                "mape": float("nan"),
                "r2": float("nan"),
                "params": params,
            }

        agg = {
            k: float(np.mean([m[k] for m in metrics_accum])) for k in metrics_accum[0]
        }
        agg["params"] = params
        return agg

    def optimize_dl_params(
        self, data_scaled, scaler, param_ranges, model_type, cv_splits=5, n_trials=20
    ):
        def objective(trial):
            params = {
                "window": trial.suggest_int(
                    "window", param_ranges["window"][0], param_ranges["window"][1]
                ),
                "hidden_size": trial.suggest_int(
                    "hidden_size",
                    param_ranges["hidden_size"][0],
                    param_ranges["hidden_size"][1],
                ),
                "num_layers": trial.suggest_int(
                    "num_layers",
                    param_ranges["num_layers"][0],
                    param_ranges["num_layers"][1],
                ),
                "dropout": trial.suggest_float(
                    "dropout",
                    param_ranges["dropout"][0],
                    param_ranges["dropout"][1],
                ),
                "lr": trial.suggest_float(
                    "lr", param_ranges["lr"][0], param_ranges["lr"][1], log=True
                ),
                "epochs": trial.suggest_int(
                    "epochs", param_ranges["epochs"][0], param_ranges["epochs"][1]
                ),
            }

            try:
                metrics = self.train_dl_cv(
                    data_scaled, scaler, params, model_type, cv_splits
                )
                return (
                    metrics["rmse"] if not np.isnan(metrics["rmse"]) else float("inf")
                )
            except Exception:
                return float("inf")

        optuna.logging.set_verbosity(optuna.logging.WARNING)
        study = optuna.create_study(direction="minimize")
        study.optimize(objective, n_trials=n_trials, show_progress_bar=False)

        best_params = study.best_params
        metrics = self.train_dl_cv(
            data_scaled, scaler, best_params, model_type, cv_splits
        )
        return best_params, metrics

    def optimize_one_variant(self, df, model_type, param_ranges):
        if model_type == "RandomForest":
            X, y = self.build_supervised(df)
            return self.optimize_rf_params(
                X, y, param_ranges, cv_splits=self.cv_splits, n_trials=50
            )

        data_scaled, scaler = self.prepare_dl_data(df)

        if len(data_scaled) < param_ranges["window"][1] + 20:
            raise ValueError(
                f"Insufficient data. Need more than {param_ranges['window'][1] + 20} samples."
            )

        return self.optimize_dl_params(
            data_scaled,
            scaler,
            param_ranges,
            model_type,
            cv_splits=self.cv_splits,
            n_trials=20,
        )

    def run(self):
        logger, log_path = self.setup_logger()
        logger.info("Starting automatic filtered experiment")

        selected_df = self.load_selection_from_summary()
        detail_ref_df = self.load_detail_reference()

        if selected_df.empty:
            logger.warning("No links selected from summary CSV.")
            return

        logger.info(f"Selected {len(selected_df)} links from {self.summary_csv}")

        all_detail_rows = []
        all_summary_rows = []

        for _, row in selected_df.iterrows():
            link = row["link"]
            baseline_method = row["best_baseline_method"]
            baseline_model = row["best_baseline_model"]
            stacking_model = row["best_stacking_model"]
            previous_improvement = row["improvement_pct"]

            logger.info(f"\n{'=' * 70}")
            logger.info(
                f"Processing link={link} | previous improvement={previous_improvement:.4f}%"
            )
            logger.info(
                f"Baseline: method={baseline_method}, model={baseline_model} | "
                f"Stacking: model={stacking_model}"
            )
            logger.info(f"{'=' * 70}")

            baseline_filename = f"{link}_baseline_{baseline_method}.csv"
            stacking_filename = f"{link}_stacking.csv"

            variants = [
                {
                    "variant": "baseline",
                    "file": baseline_filename,
                    "model_type": baseline_model,
                },
                {
                    "variant": "stacking",
                    "file": stacking_filename,
                    "model_type": stacking_model,
                },
            ]

            detail_rows = []

            for item in variants:
                variant = item["variant"]
                filename = item["file"]
                model_type = item["model_type"]

                if pd.isna(model_type):
                    logger.warning(f"[{link}][{variant}] model_type is NaN. Skipping.")
                    continue

                file_path = self.path_links / filename
                if not file_path.exists():
                    logger.warning(f"[{link}][{variant}] File not found: {file_path}")
                    continue

                ref_params = self.find_reference_params(
                    detail_ref_df, link, variant, model_type
                )
                param_ranges = self.get_param_ranges(model_type, ref_params)

                logger.info(f"[{link}][{variant}] file={filename}")
                logger.info(f"[{link}][{variant}] model={model_type}")
                logger.info(f"[{link}][{variant}] ref_params={ref_params}")
                logger.info(f"[{link}][{variant}] search_ranges={param_ranges}")

                df = self.safe_load_csv(file_path)

                try:
                    best_params, metrics = self.optimize_one_variant(
                        df, model_type, param_ranges
                    )
                except Exception as e:
                    logger.exception(f"[{link}][{variant}] optimization failed: {e}")
                    continue

                detail_row = {
                    "link": link,
                    "variant": variant,
                    "model_type": model_type,
                    "file": filename,
                    "previous_improvement_pct": previous_improvement,
                    **metrics,
                }
                all_detail_rows.append(detail_row)
                detail_rows.append(detail_row)

                logger.info(
                    f"[{link}][{variant}] best_params={best_params} | "
                    f"RMSE={metrics['rmse']:.6f} MAE={metrics['mae']:.6f} R2={metrics['r2']:.4f}"
                )

            baseline_rows = [r for r in detail_rows if r["variant"] == "baseline"]
            stacking_rows = [r for r in detail_rows if r["variant"] == "stacking"]

            if baseline_rows and stacking_rows:
                baseline_row = baseline_rows[0]
                stacking_row = stacking_rows[0]

                new_improvement = (
                    (baseline_row["rmse"] - stacking_row["rmse"])
                    / baseline_row["rmse"]
                    * 100.0
                )

                summary_row = {
                    "link": link,
                    "baseline_model_type": baseline_row["model_type"],
                    "baseline_file": baseline_row["file"],
                    "baseline_rmse": baseline_row["rmse"],
                    "stacking_model_type": stacking_row["model_type"],
                    "stacking_file": stacking_row["file"],
                    "stacking_rmse": stacking_row["rmse"],
                    "previous_improvement_pct": previous_improvement,
                    "new_improvement_pct": new_improvement,
                    "delta_improvement_pct": new_improvement - previous_improvement,
                }
                all_summary_rows.append(summary_row)

                logger.info(
                    f"[{link}] previous improvement={previous_improvement:.4f}% | "
                    f"new improvement={new_improvement:.4f}% | "
                    f"delta={new_improvement - previous_improvement:.4f} p.p."
                )

        df_detail = pd.DataFrame(all_detail_rows)
        df_detail.to_csv("models_detail_auto.csv", index=False)
        logger.info("Saved: models_detail_auto.csv")

        if all_summary_rows:
            df_summary = pd.DataFrame(all_summary_rows)
            df_summary = df_summary.sort_values("new_improvement_pct", ascending=False)
            df_summary.to_csv("models_comparison_summary_auto.csv", index=False)
            logger.info("Saved: models_comparison_summary_auto.csv")
        else:
            logger.warning("No summary rows generated.")

        logger.info(f"Complete log: {log_path}")
        logger.info("End of experiment.")
